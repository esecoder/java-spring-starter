package io.github.esecoder.jss.generator;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import io.github.esecoder.jss.config.DatabaseOption;
import io.github.esecoder.jss.config.DevTool;
import io.github.esecoder.jss.config.Template;

/**
 * Generates the Maven pom.xml or Gradle build file for the generated project.
 */
public class BuildFileWriter {

    private final String buildTool;
    private final String projectName;
    private final String groupId;
    private final String javaVersion;
    private final Template template;
    private final DatabaseOption database;
    private final List<DevTool> devtools;
    private final Path targetDir;

    public BuildFileWriter(String buildTool, String projectName, String groupId,
                           String javaVersion, Template template, DatabaseOption database,
                           List<DevTool> devtools, Path targetDir) {
        this.buildTool = buildTool;
        this.projectName = projectName;
        this.groupId = groupId;
        this.javaVersion = javaVersion;
        this.template = template;
        this.database = database;
        this.devtools = devtools;
        this.targetDir = targetDir;
    }

    public void write() throws IOException {
        if ("maven".equals(buildTool)) {
            writePom();
        } else {
            writeGradle();
        }
    }

    private boolean hasDevTool(String value) {
        return devtools.stream().anyMatch(d -> d.value().equals(value));
    }

    // ─────────────────────────────────────────────
    // Maven POM
    // ─────────────────────────────────────────────

    private void writePom() throws IOException {
        StringBuilder sb = new StringBuilder();
        sb.append("""
            <?xml version="1.0" encoding="UTF-8"?>
            <project xmlns="http://maven.apache.org/POM/4.0.0"
                     xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
                     xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 https://maven.apache.org/xsd/maven-4.0.0.xsd">
                <modelVersion>4.0.0</modelVersion>

                <parent>
                    <groupId>org.springframework.boot</groupId>
                    <artifactId>spring-boot-starter-parent</artifactId>
                    <version>3.3.0</version>
                    <relativePath/>
                </parent>

                <groupId>%s</groupId>
                <artifactId>%s</artifactId>
                <version>0.0.1-SNAPSHOT</version>
                <name>%s</name>
                <description>Generated by Java Spring Starter</description>

                <properties>
                    <java.version>%s</java.version>
            """.formatted(groupId, projectName, projectName, javaVersion));

        // Additional properties
        if (hasDevTool("springdoc")) {
            sb.append("        <springdoc.version>2.5.0</springdoc.version>\n");
        }

        sb.append("""
                </properties>

                <dependencies>
                    <!-- Spring Boot Starters -->
                    <dependency>
                        <groupId>org.springframework.boot</groupId>
                        <artifactId>spring-boot-starter-web</artifactId>
                    </dependency>
                    <dependency>
                        <groupId>org.springframework.boot</groupId>
                        <artifactId>spring-boot-starter-validation</artifactId>
                    </dependency>
                    <dependency>
                        <groupId>org.springframework.boot</groupId>
                        <artifactId>spring-boot-starter-actuator</artifactId>
                    </dependency>
            """);

        // Database dependencies
        if (database != null) {
            switch (database.value()) {
                case "h2":
                    sb.append("""
                                <!-- Database: H2 -->
                                <dependency>
                                    <groupId>org.springframework.boot</groupId>
                                    <artifactId>spring-boot-starter-data-jpa</artifactId>
                                </dependency>
                                <dependency>
                                    <groupId>com.h2database</groupId>
                                    <artifactId>h2</artifactId>
                                    <scope>runtime</scope>
                                </dependency>
                        """);
                    break;
                case "postgresql":
                    sb.append("""
                                <!-- Database: PostgreSQL -->
                                <dependency>
                                    <groupId>org.springframework.boot</groupId>
                                    <artifactId>spring-boot-starter-data-jpa</artifactId>
                                </dependency>
                                <dependency>
                                    <groupId>org.postgresql</groupId>
                                    <artifactId>postgresql</artifactId>
                                    <scope>runtime</scope>
                                </dependency>
                        """);
                    break;
                case "mysql":
                    sb.append("""
                                <!-- Database: MySQL -->
                                <dependency>
                                    <groupId>org.springframework.boot</groupId>
                                    <artifactId>spring-boot-starter-data-jpa</artifactId>
                                </dependency>
                                <dependency>
                                    <groupId>com.mysql</groupId>
                                    <artifactId>mysql-connector-j</artifactId>
                                    <scope>runtime</scope>
                                </dependency>
                        """);
                    break;
                case "mariadb":
                    sb.append("""
                                <!-- Database: MariaDB -->
                                <dependency>
                                    <groupId>org.springframework.boot</groupId>
                                    <artifactId>spring-boot-starter-data-jpa</artifactId>
                                </dependency>
                                <dependency>
                                    <groupId>org.mariadb.jdbc</groupId>
                                    <artifactId>mariadb-java-client</artifactId>
                                    <scope>runtime</scope>
                                </dependency>
                        """);
                    break;
                case "mongodb":
                    sb.append("""
                                <!-- Database: MongoDB -->
                                <dependency>
                                    <groupId>org.springframework.boot</groupId>
                                    <artifactId>spring-boot-starter-data-mongodb</artifactId>
                                </dependency>
                        """);
                    break;
            }
        }

        // Devtools dependencies
        if (hasDevTool("springdoc")) {
            sb.append("""
                        <!-- SpringDoc OpenAPI -->
                        <dependency>
                            <groupId>org.springdoc</groupId>
                            <artifactId>springdoc-openapi-starter-webmvc-ui</artifactId>
                            <version>${springdoc.version}</version>
                        </dependency>
                """);
        }

        if (hasDevTool("testcontainers")) {
            sb.append("""
                        <!-- Testcontainers -->
                        <dependency>
                            <groupId>org.testcontainers</groupId>
                            <artifactId>testcontainers</artifactId>
                            <scope>test</scope>
                        </dependency>
                        <dependency>
                            <groupId>org.testcontainers</groupId>
                            <artifactId>junit-jupiter</artifactId>
                            <scope>test</scope>
                        </dependency>
                """);
        }

        // Devtools (dev mode)
        sb.append("""
                        <dependency>
                            <groupId>org.springframework.boot</groupId>
                            <artifactId>spring-boot-devtools</artifactId>
                            <scope>runtime</scope>
                            <optional>true</optional>
                        </dependency>
                """);

        // Test
        sb.append("""
                        <!-- Test -->
                        <dependency>
                            <groupId>org.springframework.boot</groupId>
                            <artifactId>spring-boot-starter-test</artifactId>
                            <scope>test</scope>
                        </dependency>
                    </dependencies>
            """);

        // Build plugins
        sb.append("""
                <build>
                    <plugins>
                        <plugin>
                            <groupId>org.springframework.boot</groupId>
                            <artifactId>spring-boot-maven-plugin</artifactId>
                        </plugin>
            """);

        if (hasDevTool("checkstyle")) {
            sb.append("""
                            <plugin>
                                <groupId>org.apache.maven.plugins</groupId>
                                <artifactId>maven-checkstyle-plugin</artifactId>
                                <version>3.3.1</version>
                                <configuration>
                                    <configLocation>checkstyle.xml</configLocation>
                                </configuration>
                            </plugin>
                """);
        }

        if (hasDevTool("spotbugs")) {
            sb.append("""
                            <plugin>
                                <groupId>com.github.spotbugs</groupId>
                                <artifactId>spotbugs-maven-plugin</artifactId>
                                <version>4.8.5.0</version>
                            </plugin>
                """);
        }

        if (hasDevTool("spotless")) {
            sb.append("""
                            <plugin>
                                <groupId>com.diffplug.spotless</groupId>
                                <artifactId>spotless-maven-plugin</artifactId>
                                <version>2.42.0</version>
                                <configuration>
                                    <java>
                                        <removeUnusedImports/>
                                        <googleJavaFormat/>
                                    </java>
                                </configuration>
                            </plugin>
                """);
        }

        sb.append("""
                        </plugins>
                    </build>
                </project>
            """);

        Files.writeString(targetDir.resolve("pom.xml"), sb.toString());
    }

    // ─────────────────────────────────────────────
    // Gradle (Groovy DSL)
    // ─────────────────────────────────────────────

    private void writeGradle() throws IOException {
        boolean kotlin = "gradle-kotlin".equals(buildTool);
        StringBuilder sb = new StringBuilder();

        if (kotlin) {
            sb.append("""
                plugins {
                    id("java")
                    id("org.springframework.boot") version "3.3.0"
                    id("io.spring.dependency-management") version "1.1.5"
                """);
        } else {
            sb.append("""
                plugins {
                    id 'java'
                    id 'org.springframework.boot' version '3.3.0'
                    id 'io.spring.dependency-management' version '1.1.5'
                """);
        }

        if (hasDevTool("springdoc") && kotlin) {
            sb.append("    id(\"org.springdoc.openapi-gradle-plugin\") version \"1.8.0\"\n");
        } else if (hasDevTool("springdoc")) {
            sb.append("    id 'org.springdoc.openapi-gradle-plugin' version '1.8.0'\n");
        }

        if (hasDevTool("spotless") && kotlin) {
            sb.append("    id(\"com.diffplug.spotless\") version \"6.25.0\"\n");
        } else if (hasDevTool("spotless")) {
            sb.append("    id 'com.diffplug.spotless' version '6.25.0'\n");
        }

        String closingBrace = kotlin ? "}\n\n" : "}\n\n";

        sb.append(closingBrace);

        if (kotlin) {
            sb.append("""
                group = "%s"
                version = "0.0.1-SNAPSHOT"

                java {
                    toolchain {
                        languageVersion = JavaLanguageVersion.of(%s)
                    }
                }

                repositories {
                    mavenCentral()
                }

                dependencies {
                    implementation("org.springframework.boot:spring-boot-starter-web")
                    implementation("org.springframework.boot:spring-boot-starter-validation")
                    implementation("org.springframework.boot:spring-boot-starter-actuator")
                    developmentOnly("org.springframework.boot:spring-boot-devtools")
                    testImplementation("org.springframework.boot:spring-boot-starter-test")
                """.formatted(groupId, javaVersion));
        } else {
            sb.append("""
                group = '%s'
                version = '0.0.1-SNAPSHOT'

                java {
                    toolchain {
                        languageVersion = JavaLanguageVersion.of(%s)
                    }
                }

                repositories {
                    mavenCentral()
                }

                dependencies {
                    implementation 'org.springframework.boot:spring-boot-starter-web'
                    implementation 'org.springframework.boot:spring-boot-starter-validation'
                    implementation 'org.springframework.boot:spring-boot-starter-actuator'
                    developmentOnly 'org.springframework.boot:spring-boot-devtools'
                    testImplementation 'org.springframework.boot:spring-boot-starter-test'
                """.formatted(groupId, javaVersion));
        }

        // Database dependencies
        if (database != null) {
            if (kotlin) {
                addGradleDbDepsKotlin(sb);
            } else {
                addGradleDbDepsGroovy(sb);
            }
        }

        // DevTool deps
        if (hasDevTool("springdoc")) {
            if (kotlin) {
                sb.append("    implementation(\"org.springdoc:springdoc-openapi-starter-webmvc-ui:2.5.0\")\n");
            } else {
                sb.append("    implementation 'org.springdoc:springdoc-openapi-starter-webmvc-ui:2.5.0'\n");
            }
        }

        if (hasDevTool("testcontainers")) {
            if (kotlin) {
                sb.append("    testImplementation(\"org.testcontainers:testcontainers:1.19.7\")\n");
                sb.append("    testImplementation(\"org.testcontainers:junit-jupiter:1.19.7\")\n");
            } else {
                sb.append("    testImplementation 'org.testcontainers:testcontainers:1.19.7'\n");
                sb.append("    testImplementation 'org.testcontainers:junit-jupiter:1.19.7'\n");
            }
        }

        sb.append("}\n\n");

        // Spotless config
        if (hasDevTool("spotless")) {
            if (kotlin) {
                sb.append("""
                    spotless {
                        java {
                            googleJavaFormat()
                            removeUnusedImports()
                        }
                    }
                    """);
            } else {
                sb.append("""
                    spotless {
                        java {
                            googleJavaFormat()
                            removeUnusedImports()
                        }
                    }
                    """);
            }
        }

        String filename = kotlin ? "build.gradle.kts" : "build.gradle";
        Files.writeString(targetDir.resolve(filename), sb.toString());

        // Also write settings.gradle
        String settings = kotlin
            ? "rootProject.name = \"" + projectName + "\"\n"
            : "rootProject.name = '" + projectName + "'\n";
        Files.writeString(targetDir.resolve(kotlin ? "settings.gradle.kts" : "settings.gradle"), settings);
    }

    private void addGradleDbDepsGroovy(StringBuilder sb) {
        switch (database.value()) {
            case "h2":
                sb.append("    implementation 'org.springframework.boot:spring-boot-starter-data-jpa'\n");
                sb.append("    runtimeOnly 'com.h2database:h2'\n");
                break;
            case "postgresql":
                sb.append("    implementation 'org.springframework.boot:spring-boot-starter-data-jpa'\n");
                sb.append("    runtimeOnly 'org.postgresql:postgresql'\n");
                break;
            case "mysql":
                sb.append("    implementation 'org.springframework.boot:spring-boot-starter-data-jpa'\n");
                sb.append("    runtimeOnly 'com.mysql:mysql-connector-j'\n");
                break;
            case "mariadb":
                sb.append("    implementation 'org.springframework.boot:spring-boot-starter-data-jpa'\n");
                sb.append("    runtimeOnly 'org.mariadb.jdbc:mariadb-java-client'\n");
                break;
            case "mongodb":
                sb.append("    implementation 'org.springframework.boot:spring-boot-starter-data-mongodb'\n");
                break;
        }
    }

    private void addGradleDbDepsKotlin(StringBuilder sb) {
        switch (database.value()) {
            case "h2":
                sb.append("    implementation(\"org.springframework.boot:spring-boot-starter-data-jpa\")\n");
                sb.append("    runtimeOnly(\"com.h2database:h2\")\n");
                break;
            case "postgresql":
                sb.append("    implementation(\"org.springframework.boot:spring-boot-starter-data-jpa\")\n");
                sb.append("    runtimeOnly(\"org.postgresql:postgresql\")\n");
                break;
            case "mysql":
                sb.append("    implementation(\"org.springframework.boot:spring-boot-starter-data-jpa\")\n");
                sb.append("    runtimeOnly(\"com.mysql:mysql-connector-j\")\n");
                break;
            case "mariadb":
                sb.append("    implementation(\"org.springframework.boot:spring-boot-starter-data-jpa\")\n");
                sb.append("    runtimeOnly(\"org.mariadb.jdbc:mariadb-java-client\")\n");
                break;
            case "mongodb":
                sb.append("    implementation(\"org.springframework.boot:spring-boot-starter-data-mongodb\")\n");
                break;
        }
    }
}
